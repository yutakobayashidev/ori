import { writeFileSync } from 'node:fs'
import { readMigrationFiles } from 'drizzle-orm/migrator'

const migrations = readMigrationFiles({
  migrationsFolder: new URL('../drizzle', import.meta.url).pathname,
})
writeFileSync(
  new URL('../src/features/storage/migrations.generated.ts', import.meta.url),
  `// Generated by pnpm db:generate. Do not edit.\nexport const migrations = ${JSON.stringify(migrations, null, 2)}\n`,
)
